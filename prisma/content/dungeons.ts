export interface MonsterDropDefinition {
  itemName: string;
  baseChance: number;
  minQuantity: number;
  maxQuantity: number;
  /** Character level. */
  requiredLevel: number;
}

export interface MonsterDefinition {
  name: string;
  description: string;
  asset: string;
  attackStyle: CreatureAttackStyle;
  damageMin: number;
  damageMax: number;
  magicDamageMin: number;
  magicDamageMax: number;
  damageType: CreatureDamageType | null;
  elementalDamageMin: number;
  elementalDamageMax: number;
  health: number;
  armor: number;
  magicResist: number;
  evasion: number;
  blockChance: number;
  critChance: number;
  critDamage: number;
  drops: readonly MonsterDropDefinition[];
}

export interface DungeonDefinition {
  name: string;
  locationName: AtlasLocationName | (typeof ADMIN_LOCATION_NAMES)[number];
  /** Renamed live-location labels accepted by the additive seeder. */
  locationAliases?: readonly string[];
  description: string;
  difficulty: DungeonDifficulty;
  requiredLevel: number;
  durationSeconds: number;
  /** Monsters fighting the character at once; 1 = one at a time. */
  packSize: number;
  xpReward: number;
  sortOrder: number;
  /** `enabled: false` switches off a placement left by older content. */
  monsters: readonly {
    name: string;
    minCount: number;
    maxCount: number;
    enabled?: boolean;
  }[];
}

